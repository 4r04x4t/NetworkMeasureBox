"""IPv6 for the LAN and Wi-Fi in router mode: a delegated prefix from the ISP, advertised to the clients.

The ISP's PPPoE line (2026-11-09, DIGI) gives the box its own address by a router advert on ppp0 and a
/64 for the LAN by DHCPv6 prefix delegation. dhcpcd asks for that prefix on the WAN and puts it on the
LAN bridge; dnsmasq advertises it there (SLAAC, with the box as DNS server in the advert). The firewall
lets the LAN out and only answers back in (nmb/netd/firewall.py), as for IPv4.

Off with `[network] lan_ipv6 = false`. Only for a PPPoE WAN for now: a hotspot on USB or a WAN behind
another router seldom delegates a prefix.
"""
from __future__ import annotations

import shutil
import subprocess
from pathlib import Path
from typing import List

DHCPCD_PATHS = ("/usr/sbin/dhcpcd", "/sbin/dhcpcd")


def dhcpcd_bin() -> str:
    return shutil.which("dhcpcd") or next((p for p in DHCPCD_PATHS if Path(p).exists()), "")


def dhcpcd_conf(wan_iface: str, lan_iface: str) -> str:
    """Prefix delegation only: no IPv4, no router solicitations (the kernel takes the WAN's own advert),
    no changes to resolv.conf, the host name or NTP."""
    return "\n".join([
        "# Auto-generated by NetworkMeasureBox netd: IPv6 prefix for the LAN",
        f"allowinterfaces {wan_iface}",
        "ipv6only",
        "noipv6rs",
        "nohook resolv.conf hostname ntp wpa_supplicant",
        "duid",
        "option rapid_commit",
        f"interface {wan_iface}",
        f"    ia_pd 1 {lan_iface}/0/64",
        "",
    ])


def dnsmasq_ra_lines(lan_ifaces: List[str]) -> str:
    """dnsmasq advertises whatever global prefix is on the LAN interface (SLAAC), and itself as DNS."""
    if not lan_ifaces:
        return ""
    lines = ["# IPv6 for the LAN: router adverts with the delegated prefix (nmb/netd/ipv6_lan.py)", "enable-ra"]
    for iface in lan_ifaces:
        lines.append(f"dhcp-range=::,constructor:{iface},ra-stateless,ra-names,64,12h")
    lines.append("dhcp-option=option6:dns-server,[::]")
    return "\n".join(lines) + "\n"


def lan_prefixes(iface: str) -> List[str]:
    """Global IPv6 networks on iface (what the LAN clients get), as text without the host part."""
    out = subprocess.run(["ip", "-6", "-o", "addr", "show", "dev", iface, "scope", "global"],
                         capture_output=True, text=True, timeout=5, check=False).stdout
    nets = []
    for line in out.splitlines():
        parts = line.split()
        if "inet6" in parts:
            nets.append(parts[parts.index("inet6") + 1])
    return nets
