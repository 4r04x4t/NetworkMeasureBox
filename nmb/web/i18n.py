def get_translations_for_lang(lang: str) -> Dict[str, str]:
    """Return dictionary of translations for specified language code, falling back to English."""
    lang_code = (lang or DEFAULT_LANGUAGE).lower()
    if lang_code in TRANSLATIONS:
        # Overlay on top of English for safety
        merged = dict(TRANSLATIONS["en"])
        merged.update(TRANSLATIONS[lang_code])
        return merged
    return TRANSLATIONS["en"]
