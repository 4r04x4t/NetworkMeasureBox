def get_translations_for_lang(lang: str) -> dict[str, str]:
    """Retrieve full translations dictionary for a given language code with fallback to EN."""
    base = dict(TRANSLATIONS.get(DEFAULT_LANGUAGE, {}))
    if lang in TRANSLATIONS and lang != DEFAULT_LANGUAGE:
        base.update(TRANSLATIONS[lang])
    return base

def get_translation(key: str, lang: str = DEFAULT_LANGUAGE, default: str = "") -> str:
    """Retrieve localized string for given key and language code."""
    d = TRANSLATIONS.get(lang) or TRANSLATIONS.get(DEFAULT_LANGUAGE, {})
    return d.get(key) or TRANSLATIONS.get(DEFAULT_LANGUAGE, {}).get(key) or default or key
